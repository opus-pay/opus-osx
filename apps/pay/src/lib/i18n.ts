export const MESSAGES: Record<Locale, Messages> = { en, ko, ja, zh };

export function isLocale(value: unknown): value is Locale {
    return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

/** The first browser language we speak, else English. "zh-TW" falls back to Simplified Chinese. */
export function pickLocale(languages: readonly string[]): Locale {
    for (const language of languages) {
        const base = language.toLowerCase().split("-")[0];
        if (isLocale(base)) return base;
    }
    return "en";
}

/** The text for `key` in `locale`, with `{name}` slots filled from `vars`. */
export function translate(locale: Locale, key: MessageKey, vars: Record<string, string | number> = {}): string {
    const text = MESSAGES[locale][key] ?? en[key];
    return text.replace(/\{(\w+)\}/g, (slot, name: string) => (name in vars ? String(vars[name]) : slot));
}

/** Known English error messages (link validation) in the reader's language; others pass through. */
export function localizeError(locale: Locale, message: string): string {
    for (const key of Object.keys(en) as MessageKey[]) {
        if (key.startsWith("error.") && en[key] === message) return translate(locale, key);
    }
    return message;
}
